namespace CodingAgent.Pipeline.Models;

/// <summary>Recognizes the refactoring scan's issues by the footer every one of them carries.</summary>
public static class RefactoringScanIssues
{
    /// <summary>
    /// The footer sentence every refactoring scan issue carries. Used to distinguish scan issues
    /// from other issues (e.g. decomposition sub-issues) without a dedicated label.
    /// Issues filed before this constant existed carry it too.
    /// </summary>
    public const string Footer = "This issue was automatically generated by the refactoring detection consolidation loop";

    /// <summary>
    /// Returns <see langword="true"/> when <paramref name="issue"/> was created by the refactoring
    /// detection scan (identified by the <see cref="Footer"/> in its description).
    /// </summary>
    public static bool IsScanIssue(IssueSummary issue) =>
        issue.Description?.Contains(Footer, StringComparison.Ordinal) == true;
}
